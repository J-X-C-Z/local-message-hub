import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,mkdirSync,writeFileSync,rmSync} from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import {EventStore} from '../backend/wecom-mcp/src/store.js';
import {startLocalReader} from '../backend/local-reader.mjs';

const waitUntil=async predicate=>{for(let i=0;i<80;i++){if(predicate())return;await new Promise(resolve=>setTimeout(resolve,100));}throw new Error('等待文件通知超时');};
test('文件通知导入、重复去重及迟到消息保留', {timeout:15000}, async t=>{
 const directory=mkdtempSync(path.join(os.tmpdir(),'local-reader-'));
 const source=path.join(directory,'source');mkdirSync(source);
 const privateDir=path.join(directory,'local-reading');mkdirSync(privateDir);
 writeFileSync(path.join(privateDir,'profile-path.txt'),source);writeFileSync(path.join(privateDir,'database-key.dpapi'),'fixture');
 const filename=path.join(source,'message.db');
 const now=Math.floor(Date.now()/1000);
 const item=(key,time,conversation)=>({key,payload:{Source:'local-database',ConversationId:conversation,ConversationName:conversation,ConversationType:'group',FromUserName:'member',CreateTime:time,MsgType:'text',Content:key}});
 let messages=[item('one',now,'group-a')];
 const save=()=>writeFileSync(filename,JSON.stringify({type:'snapshot',messages,total:messages.length,conversations:2}));save();
 const fixture=path.join(directory,'fixture.cjs');
 writeFileSync(fixture,"const fs=require('node:fs');const rl=require('node:readline');const refresh=()=>{console.log(fs.readFileSync(process.argv[2],'utf8'));console.log(JSON.stringify({type:'health',ok:true}));};refresh();rl.createInterface({input:process.stdin}).on('line',refresh);");
 const store=new EventStore(path.join(directory,'events.db'));
 const reader=startLocalReader({directory,executable:process.execPath,args:[fixture,filename],store});
 t.after(async()=>{await reader.stop();store.close();rmSync(directory,{recursive:true,force:true});});
 await waitUntil(()=>store.list().events.length===1);
 save();await new Promise(resolve=>setTimeout(resolve,850));assert.equal(store.list().events.length,1);
 messages.push(item('late',now-60,'group-b'));save();
 await waitUntil(()=>store.list().events.length===2);
 assert.equal(store.list().events[1].message.Content,'late');
 assert.equal(store.list().events[1].message.ConversationId,'group-b');
 assert.equal(store.db.prepare("SELECT value FROM receiver_state WHERE key='source'").get().value,'local-database');
 const previous=store.list().events[0];
 messages[0].payload={...messages[0].payload,Content:'邀请人 邀请 新成员 加入群聊',System:true};save();
 await waitUntil(()=>store.list().events[0].message.System===true);
 const repaired=store.list().events[0];
 assert.equal(repaired.id,previous.id);
 assert.equal(repaired.received_at,previous.received_at);
 assert.equal(store.list().events.length,2);
});
